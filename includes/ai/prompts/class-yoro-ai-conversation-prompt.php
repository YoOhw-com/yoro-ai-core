			'Operational queues: operations attention, customer service, fulfillment, inventory.',
			'Order review: show order details, search orders, inspect recent orders.',
			'Order actions: add notes, update status, put orders on hold, guided follow-up previews.',
			'Workflow actions: suspicious-order review, refund review, verify customer before fulfillment, hold with note, status with note, and write email workflows for an order.',
			'Customer email work: compose, preview, save drafts, update drafts, send customer emails.',
			'Refund preview and selected workflow previews that already exist inside YoRo.',
		];
		$read_only_action_allowlist = [
			'orders.get_details',
			'orders.search',
			'customers.get_summary',
			'orders.find_by_customer',
			'orders.find_by_identity',
			'store.get_morning_briefing',
			'store.get_daily_briefing',
			'store.get_business_summary',
			'store.get_insights',
			'operations.get_summary',
