				'- Use "third_party_crm_and_team_integrations" for Slack, HubSpot, CRM, sync, and external integrations.',
				'- Use "order_authoring" for creating new orders, draft orders, or manual orders.',
				'- Use "general_world_knowledge" for news, weather, sports, biographies, opinions, or general knowledge outside store operations.',
