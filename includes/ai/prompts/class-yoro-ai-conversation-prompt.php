							? count( $context['last_inventory_followup']['recommended_sequence'] )
							: 0,
						'inventory_cursor' => isset( $context['last_inventory_followup']['recommendation_cursor'] ) ? (int) $context['last_inventory_followup']['recommendation_cursor'] : -1,
						'briefing_recommendations' => ! empty( $context['last_briefing']['recommended_sequence'] ) && is_array( $context['last_briefing']['recommended_sequence'] )
							? count( $context['last_briefing']['recommended_sequence'] )
							: 0,
						'briefing_cursor' => isset( $context['last_briefing']['recommendation_cursor'] ) ? (int) $context['last_briefing']['recommendation_cursor'] : -1,
					],
				],
			]
			);

